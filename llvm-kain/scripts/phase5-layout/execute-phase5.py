def sandbox_rel_path(abs_path_obj: Path, sandbox_root: Path) -> str:
    """Convert a path under the sandbox to sandbox-relative."""
    try:
        return normalize_path(str(abs_path_obj.relative_to(sandbox_root)))
    except ValueError:
        return normalize_path(str(abs_path_obj))


def resolve_include_path(inc_path: str) -> str:
    """Resolve an include path to its new location under the target layout.
    Returns the new path or empty string if unresolvable/dropped."""
    norm_inc = normalize_path(inc_path)
    for old_prefix, new_prefix in SORTED_INCLUDE_MAP:
        if norm_inc.startswith(old_prefix):
            if new_prefix == "":
                return ""
            suffix = norm_inc[len(old_prefix):]
            return new_prefix + suffix
    if norm_inc.startswith("llvm/"):
        remainder = norm_inc[5:]
        for old_prefix, new_prefix in SORTED_INCLUDE_MAP:
            if old_prefix.startswith("llvm/") and remainder.startswith(old_prefix[5:]):
                suffix = remainder[len(old_prefix[5:]):]
                return new_prefix + suffix
    if norm_inc.startswith("clang/"):
        remainder = norm_inc[6:]
        for old_prefix, new_prefix in SORTED_INCLUDE_MAP:
            if old_prefix.startswith("clang/") and remainder.startswith(old_prefix[6:]):
                suffix = remainder[len(old_prefix[6:]):]
                return new_prefix + suffix
    return inc_path


