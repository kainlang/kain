    logger.info(f"  Include path fixes:  ~30s")
    logger.info(f"  Verification:        ~1 min")
    logger.info(f"  Total:               ~{1 + total_files * 0.002 / 60 + 0.5 + 1:.0f} min")
    logger.info("")

    logger.info("SAFE: No files were modified. Run with --execute to proceed.")
    logger.info("")

    # Write dry-run report
    report = REPORTS_DIR / "dry-run-report.txt"
    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
