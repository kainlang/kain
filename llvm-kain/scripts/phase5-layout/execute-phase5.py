    # Only clean directories that had ALL their files copied
    source_dirs_used = defaultdict(set)
    source_dirs_all = defaultdict(set)
    for m in moves:
        src_raw = m.get("current_path", "")
        tgt_raw = m.get("target_path", "")
        if src_raw and tgt_raw and tgt_raw != "(keep-in-place)":
            src_dir = os.path.dirname(normalize_path(src_raw))
            src_abs = str(LLVM_PROJECT_ROOT / src_dir)
            source_dirs_used[src_abs].add(1)
            # Check if the source file still exists (it should — we copied, not moved)
            src_file = str(LLVM_PROJECT_ROOT / normalize_path(src_raw))
            source_dirs_all[src_abs].add(src_file)

    # Only clean directories under areas we moved from
    clean_areas = [
        "llvm/lib/IR", "llvm/lib/Analysis", "llvm/lib/Transforms",
        "llvm/lib/CodeGen", "llvm/lib/MC", "llvm/lib/Object",
        "llvm/lib/Support", "llvm/lib/Target/X86", "llvm/lib/Target/AArch64",
        "llvm/lib/ExecutionEngine/Orc", "llvm/lib/ExecutionEngine/JITLink",
        "llvm/include/llvm", "llvm/include/llvm-c",
        "clang/lib", "clang/include/clang",
        "compiler-rt/lib/builtins",
    ]

    empty_removed = 0
    for clean_area in clean_areas:
        clean_path = LLVM_PROJECT_ROOT / normalize_path(clean_area)
        if not clean_path.exists():
            continue
        # Walk bottom-up and remove empty directories
        for root, dirs, files in os.walk(str(clean_path), topdown=False):
            if not os.path.exists(root):
                continue
            if root == str(clean_path):
                continue
            try:
                # Check if directory is empty (no files, no subdirs)
                remaining = os.listdir(root)
                if not remaining:
                    os.rmdir(root)
                    empty_removed += 1
            except (OSError, PermissionError):
                pass

    logger.info(f"  Empty directories removed: {empty_removed}")
    save_checkpoint({**load_checkpoint(), "phase4_empty_removed": empty_removed})

