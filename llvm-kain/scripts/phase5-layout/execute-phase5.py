def mode_backup(logger: logging.Logger):
    """Create a full backup of the llvm-project tree."""
    if not LLVM_PROJECT_ROOT.exists():
        logger.error(f"Source tree not found: {LLVM_PROJECT_ROOT}")
        return False

    timestamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    backup_path = BACKUP_ROOT / f"llvm-project-{timestamp}"
    newest_backup = find_newest_backup()

    # Check if a backup already exists for today
    today_prefix = datetime.now().strftime("%Y%m%d")
    today_backups = sorted(BACKUP_ROOT.glob(f"llvm-project-{today_prefix}-*"))
    if today_backups:
        logger.warning(f"Backup already exists for today: {today_backups[-1]}")
        answer = input("Overwrite? (y/N): ").strip().lower()
        if answer != "y":
            logger.info("Backup cancelled.")
            return True

    logger.info(f"Creating backup of {LLVM_PROJECT_ROOT}")
    logger.info(f"  -> {backup_path}")
    logger.info("")

    # Estimate size
    total_files = 0
    total_size = 0
    logger.info("Scanning source tree...")
    for root, dirs, files in os.walk(str(LLVM_PROJECT_ROOT)):
        # Skip hidden directories
        dirs[:] = [d for d in dirs if not d.startswith(".") and d != "__pycache__"]
        for fname in files:
            try:
                fp = os.path.join(root, fname)
                total_files += 1
                total_size += os.path.getsize(fp)
            except (OSError, PermissionError):
                pass

    logger.info(f"  Files to backup: {total_files:,}")
    logger.info(f"  Size to backup:  {total_size / 1024 / 1024:.1f} MB")
    logger.info("")

    # Create parent
    BACKUP_ROOT.mkdir(parents=True, exist_ok=True)

    # Do the copy
    logger.info("Starting backup (this may take a while)...")
    start_time = time.time()

    try:
        shutil.copytree(
            str(LLVM_PROJECT_ROOT),
            str(backup_path),
            symlinks=False,
            ignore_dangling_symlinks=True,
            ignore=shutil.ignore_patterns("__pycache__", ".git"),
        )
    except Exception as e:
        logger.error(f"Backup failed: {e}")
        return False

    elapsed = time.time() - start_time
    logger.info(f"Backup complete in {elapsed:.0f}s")

    # Write backup report
    report = REPORTS_DIR / "backup-report.txt"
    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    with open(report, "w") as f:
        f.write(f"Backup Report\n")
        f.write(f"=============\n")
        f.write(f"Date:     {datetime.now().isoformat()}\n")
        f.write(f"Source:   {LLVM_PROJECT_ROOT}\n")
        f.write(f"Backup:   {backup_path}\n")
        f.write(f"Files:    {total_files:,}\n")
        f.write(f"Size:     {total_size / 1024 / 1024:.1f} MB\n")
        f.write(f"Duration: {elapsed:.0f}s\n")

    logger.info(f"Backup report written to: {report}")
    save_checkpoint({
        "backup_path": str(backup_path),
        "backup_time": datetime.now().isoformat(),
        "backup_files": total_files,
        "backup_size": total_size,
    })
    return True


def find_newest_backup() -> Path | None:
    """Find the most recent backup directory."""
    if not BACKUP_ROOT.exists():
        return None
    backups = sorted(BACKUP_ROOT.glob("llvm-project-*"))
    return backups[-1] if backups else None


