def mode_reverse(logger: logging.Logger):
    """Restore from backup."""
    checkpoint = load_checkpoint()
    backup_path_str = checkpoint.get("backup_path")
    if not backup_path_str:
        newest = find_newest_backup()
        if not newest:
            logger.error("No backup found! Run --backup first.")
            logger.error("  python execute-phase5.py --backup")
            return False
        backup_path = newest
        logger.info(f"Found backup at: {backup_path}")
        answer = input("Use this backup? (Y/n): ").strip().lower()
        if answer == "n":
            logger.info("Reverse cancelled.")
            return False
    else:
        backup_path = Path(backup_path_str)
        if not backup_path.exists():
            logger.error(f"Backup path not found: {backup_path}")
            logger.error("Run --backup to create a new backup.")
            return False

    logger.info("=" * 70)
    logger.info("PHASE 5 LAYOUT RESTRUCTURE — REVERSE")
    logger.info(f"Restoring from: {backup_path}")
    logger.info("=" * 70)
    logger.info("")

    logger.warning("This will DELETE the llvm-kain/ directory and RESTORE")
    logger.warning("the original llvm-project/ from backup.")
    logger.warning("ALL changes since the backup will be LOST.")
    answer = input("Are you absolutely sure? (yes/N): ").strip().lower()
    if answer != "yes":
        logger.info("Reverse cancelled.")
        return False

    # Remove llvm-kain/
    if LLVM_KAIN_DIR.exists():
        logger.info("Removing llvm-kain/ directory...")
        try:
            shutil.rmtree(str(LLVM_KAIN_DIR))
            logger.info("  Removed.")
        except Exception as e:
            logger.error(f"  Failed to remove {LLVM_KAIN_DIR}: {e}")
            return False

    # Remove the current tree completely
    logger.info("Removing current llvm-project/ contents (keeping .git if exists)...")
    git_dir = LLVM_PROJECT_ROOT / ".git"
    has_git = git_dir.exists()

    for item in LLVM_PROJECT_ROOT.iterdir():
        if item.name == ".git":
            continue
        try:
            if item.is_dir():
                shutil.rmtree(str(item))
            else:
                item.unlink()
        except Exception as e:
            logger.warning(f"  Could not remove {item.name}: {e}")

    # Copy everything back from backup
    logger.info(f"Restoring from backup: {backup_path}")
    start_time = time.time()

    try:
        shutil.copytree(
            str(backup_path),
            str(LLVM_PROJECT_ROOT),
            symlinks=False,
            ignore_dangling_symlinks=True,
            dirs_exist_ok=True,
            ignore=shutil.ignore_patterns("__pycache__", ".git"),
        )
    except Exception as e:
        logger.error(f"Restore failed: {e}")
        return False

    elapsed = time.time() - start_time
    logger.info(f"Restore complete in {elapsed:.0f}s")

    # Clear checkpoint
    clear_checkpoint()

    # Write reverse log
    reverse_log = REPORTS_DIR / "reverse-log.txt"
    with open(reverse_log, "w") as f:
        f.write(f"Phase 5 Reverse Log\n")
        f.write(f"==================\n")
        f.write(f"Date:       {datetime.now().isoformat()}\n")
        f.write(f"Backup:     {backup_path}\n")
        f.write(f"Duration:   {elapsed:.0f}s\n")
        f.write(f"Status:     Restored from backup\n")
    logger.info(f"Reverse log written to: {reverse_log}")
    return True


