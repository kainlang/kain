def mode_sandbox_apply(logger: logging.Logger):
    """Apply the layout restructure INSIDE the sandbox only."""
    if not SANDBOX_SRC_DIR.exists():
        logger.error(f"Sandbox not found at {SANDBOX_SRC_DIR}")
        logger.error("Run --sandbox-prep first.")
        return False

    movements = load_file_movements()
    if not movements:
        logger.error(f"No file movements found at {FILE_MOVEMENTS_TSV}")
        return False

    moves = [m for m in movements if m.get("action") == "move"]
    logger.info("=" * 70)
    logger.info("SANDBOX — APPLY LAYOUT RESTRUCTURE")
    logger.info(f"Inside: {SANDBOX_SRC_DIR}")
    logger.info(f"Target: {SANDBOX_KAIN_DIR}")
    logger.info("=" * 70)
    logger.info("")

    start_time = time.time()
    total_errors = 0

    # ── Phase 1: Create target directories ──────────────────────────────────
    logger.info("Phase 1/4: Creating target directories in sandbox...")
    target_dirs = set()
    for m in moves:
        tgt = m.get("target_path", "")
        if tgt and tgt != "(keep-in-place)":
            if tgt.startswith("llvm-kain/"):
                local = tgt[len("llvm-kain/"):]
                td = os.path.dirname(str(SANDBOX_KAIN_DIR / local))
            else:
                td = os.path.dirname(str(SANDBOX_KAIN_DIR / tgt.replace(f"llvm-kain/", "", 1)))
            target_dirs.add(td)

    created = 0
    for td in sorted(target_dirs):
        os.makedirs(td, exist_ok=True)
        created += 1
    logger.info(f"  Created {created} directories.")

    # ── Phase 2: Copy files to new layout ───────────────────────────────────
    logger.info("")
    logger.info("Phase 2/4: Copying files to new layout in sandbox...")
    copied = 0
    skipped = 0
    errors = []

    pb = ProgressBar(len(moves), prefix="Copying (sandbox)")
    for m in moves:
        src_raw = m.get("current_path", "")
        tgt_raw = m.get("target_path", "")
        if not src_raw or not tgt_raw or tgt_raw == "(keep-in-place)":
            skipped += 1
            pb.update()
            continue

        src_path = SANDBOX_SRC_DIR / normalize_path(src_raw)
        tgt_path = SANDBOX_SRC_DIR / normalize_path(tgt_raw)

        if not src_path.exists():
            errors.append(f"Source not found: {src_path}")
            total_errors += 1
            pb.update()
            continue

        if tgt_path.exists():
            skipped += 1
            pb.update()
            continue

        try:
            tgt_path.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(str(src_path), str(tgt_path))
            copied += 1
        except Exception as e:
            errors.append(f"Copy failed: {src_path} -> {tgt_path}: {e}")
            total_errors += 1
        pb.update()
    pb.close()

    logger.info(f"  Copied:  {copied:,}")
    logger.info(f"  Skipped: {skipped:,}")
    logger.info(f"  Errors:  {total_errors}")

    if errors:
        for err in errors[:10]:
            logger.warning(f"    - {err}")

    # ── Phase 3: Fix include paths ──────────────────────────────────────────
    logger.info("")
    logger.info("Phase 3/4: Fixing include paths in sandbox...")
    include_fixes = 0
    include_errors = 0

    src_files = []
    for ext in SOURCE_EXTENSIONS:
        src_files.extend(SANDBOX_KAIN_DIR.rglob(f"*{ext}"))

    pb = ProgressBar(len(src_files), prefix="Fixing includes")
    include_rewrites = []
    for sf in src_files:
        sf_str = str(sf)
        try:
            with open(sf_str, "r", encoding="utf-8", errors="replace") as f:
                content = f.read()
            original = content
            modified = False

            def replacer(match):
                nonlocal modified
                prefix = match.group(1)
                inc_path = match.group(2)
                suffix = match.group(3)
                resolved = resolve_include_path(inc_path)
                if resolved and resolved != inc_path:
                    modified = True
                    return prefix + resolved + suffix
                return match.group(0)

            content = INCLUDE_RE.sub(replacer, content)

            if modified:
                with open(sf_str, "w", encoding="utf-8") as f:
                    f.write(content)
                include_fixes += 1
                inc_rel = sandbox_rel_path(sf, SANDBOX_SRC_DIR)
                include_rewrites.append(inc_rel)
        except Exception as e:
            include_errors += 1
            total_errors += 1
        pb.update()
    pb.close()

    logger.info(f"  Files with include fixes: {include_fixes:,}")
    logger.info(f"  Include fix errors:       {include_errors}")

    # Write include rewrites log
    inc_log = REPORTS_DIR / "sandbox-include-rewrites.log"
    with open(inc_log, "w") as f:
        for path in sorted(include_rewrites):
            f.write(path + "\n")
    logger.info(f"  Include rewrites log: {inc_log}")

    # ── Phase 4: Remove empty source directories ────────────────────────────
    logger.info("")
    logger.info("Phase 4/4: Cleaning up empty source directories in sandbox...")
    clean_areas = [
        "llvm/lib/IR", "llvm/lib/Analysis", "llvm/lib/Transforms",
        "llvm/lib/CodeGen", "llvm/lib/MC", "llvm/lib/Object",
        "llvm/lib/Support", "llvm/lib/Target/X86", "llvm/lib/Target/AArch64",
        "llvm/lib/ExecutionEngine/Orc", "llvm/lib/ExecutionEngine/JITLink",
        "llvm/include/llvm", "llvm/include/llvm-c",
        "clang/lib", "clang/include/clang",
        "compiler-rt/lib/builtins",
    ]
    empty_removed = 0
    for clean_area in clean_areas:
        clean_path = SANDBOX_SRC_DIR / normalize_path(clean_area)
        if not clean_path.exists():
            continue
        for root, dirs, files in os.walk(str(clean_path), topdown=False):
            if not os.path.exists(root):
                continue
            if root == str(clean_path):
                continue
            try:
                remaining = os.listdir(root)
                if not remaining:
                    os.rmdir(root)
                    empty_removed += 1
            except (OSError, PermissionError):
                pass

    logger.info(f"  Empty directories removed: {empty_removed}")

    elapsed = time.time() - start_time
    logger.info("")
    logger.info("=" * 70)
    logger.info("SANDBOX APPLY SUMMARY")
    logger.info(f"  Duration:        {elapsed:.0f}s")
    logger.info(f"  Directories:     {created:,}")
    logger.info(f"  Files copied:    {copied:,}")
    logger.info(f"  Already existed: {skipped:,}")
    logger.info(f"  Include fixes:   {include_fixes:,}")
    logger.info(f"  Empty dirs removed: {empty_removed:,}")
    logger.info(f"  Errors:          {total_errors}")
    logger.info("=" * 70)

    # Write apply log
    apply_log = REPORTS_DIR / "sandbox-apply-log.txt"
    with open(apply_log, "w") as f:
        f.write(f"Sandbox Apply Log\n")
        f.write(f"================\n")
        f.write(f"Date:             {datetime.now().isoformat()}\n")
        f.write(f"Duration:         {elapsed:.0f}s\n")
        f.write(f"Directories:      {created:,}\n")
