# ============================================================================
# PATH HELPERS
# ============================================================================

def normalize_path(p: str) -> str:
    """Normalize path separators to forward slashes."""
    return p.replace("\\", "/").replace("//", "/")


def abs_path(rel_path: str) -> Path:
    """Convert a repo-relative path to absolute."""
    norm = normalize_path(rel_path)
    return Path(LLVM_PROJECT_ROOT / norm).resolve()


def rel_path(abs_path_obj: Path) -> str:
    """Convert an absolute path to repo-relative."""
    try:
        return normalize_path(str(abs_path_obj.relative_to(LLVM_PROJECT_ROOT)))
    except ValueError:
        return normalize_path(str(abs_path_obj))

# ============================================================================
# SANDBOX MODES
# ============================================================================
# These modes operate inside temp-build/ only. The real llvm-project/ is
# NEVER modified by sandbox operations.
