def mode_sandbox_prep(logger: logging.Logger):
    """Copy only Phase-5-relevant files into sandbox: files from the movement
    TSV plus CMake/build infrastructure. Skips large research/scratch artifacts."""
    if not LLVM_PROJECT_ROOT.exists():
        logger.error(f"Source tree not found: {LLVM_PROJECT_ROOT}")
        return False

    movements = load_file_movements()
    if not movements:
        logger.error(f"No file movements found at {FILE_MOVEMENTS_TSV}")
        logger.error("Run analysis scripts first.")
        return False

    # Check if sandbox already exists
    if SANDBOX_SRC_DIR.exists():
        logger.warning(f"Sandbox already exists at {SANDBOX_SRC_DIR}")
        answer = input("Overwrite? (y/N): ").strip().lower()
        if answer != "y":
            logger.info("Sandbox prep cancelled.")
            return True
        logger.info("Removing existing sandbox...")
        shutil.rmtree(str(SANDBOX_DIR))

    logger.info(f"Copying Phase-5-relevant files to sandbox...")
    logger.info(f"  Source: {LLVM_PROJECT_ROOT}")
    logger.info(f"  Dest:   {SANDBOX_SRC_DIR}")
    logger.info("")

    start_time = time.time()
    SANDBOX_DIR.mkdir(parents=True, exist_ok=True)

    # Build a set of source paths that must be copied (from the movement TSV)
    needed_paths = {}
    for m in movements:
        src_raw = m.get("current_path", "")
        if src_raw and src_raw != "(keep-in-place)":
            src_abs = str(LLVM_PROJECT_ROOT / normalize_path(src_raw))
            needed_paths[src_abs] = True

    # Also copy essential build infrastructure (CMakeLists.txt at key dirs)
    build_dirs = [
        "llvm/lib/IR", "llvm/lib/Analysis", "llvm/lib/Transforms",
        "llvm/lib/CodeGen", "llvm/lib/MC", "llvm/lib/Object",
        "llvm/lib/Support", "llvm/lib/Target/X86", "llvm/lib/Target/AArch64",
        "llvm/lib/ExecutionEngine/Orc", "llvm/lib/ExecutionEngine/JITLink",
        "llvm/include/llvm", "llvm/include/llvm-c",
        "clang/lib", "clang/include/clang",
        "compiler-rt/lib/builtins",
        "lld", "cmake", "runtimes",
    ]

    # Collect all CMakeLists.txt and .cmake files from build areas
    extra_patterns = ["CMakeLists.txt", "*.cmake", "*.inc"]
    import fnmatch
    for bd in build_dirs:
        bd_path = LLVM_PROJECT_ROOT / normalize_path(bd)
        if not bd_path.exists():
            continue
        for r, dirs, files in os.walk(str(bd_path)):
            for f in files:
                for pat in extra_patterns:
                    if fnmatch.fnmatch(f, pat):
                        fp = os.path.join(r, f)
                        needed_paths[fp] = True
                        break

    # Sort and copy
    sorted_srcs = sorted(needed_paths.keys())
    total_files = len(sorted_srcs)
    total_size = 0

    pb = ProgressBar(total_files, prefix="Copying to sandbox")
    copied = 0
    errors = 0

    for src_abs in sorted_srcs:
        try:
            total_size += os.path.getsize(src_abs)
            rel = os.path.relpath(src_abs, str(LLVM_PROJECT_ROOT))
            dst_abs = str(SANDBOX_SRC_DIR / normalize_path(rel))
            os.makedirs(os.path.dirname(dst_abs), exist_ok=True)
            shutil.copy2(src_abs, dst_abs)
            copied += 1
        except Exception as e:
            errors += 1
            if errors <= 5:
                logger.warning(f"  Copy error: {src_abs}: {e}")
        pb.update()
    pb.close()

    elapsed = time.time() - start_time
    logger.info(f"")
    logger.info(f"Sandbox copy complete in {elapsed:.0f}s")
    logger.info(f"  Copied:  {copied:,}")
    logger.info(f"  Errors:  {errors}")
    logger.info(f"  Size:    {total_size / 1024 / 1024:.1f} MB")

    # Write report
    report = REPORTS_DIR / "sandbox-prep-log.txt"
    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    with open(report, "w") as f:
        f.write(f"Sandbox Prep Log\n")
        f.write(f"================\n")
        f.write(f"Date:     {datetime.now().isoformat()}\n")
        f.write(f"Source:   {LLVM_PROJECT_ROOT}\n")
        f.write(f"Sandbox:  {SANDBOX_SRC_DIR}\n")
        f.write(f"Files:    {copied:,}\n")
        f.write(f"Size:     {total_size / 1024 / 1024:.1f} MB\n")
        f.write(f"Duration: {elapsed:.0f}s\n")
        f.write(f"Errors:   {errors}\n")

    save_checkpoint({**load_checkpoint(),
        "sandbox_path": str(SANDBOX_SRC_DIR),
        "sandbox_prep_time": datetime.now().isoformat(),
        "sandbox_files": copied,
        "sandbox_size": total_size,
    })
    logger.info(f"Sandbox prep report: {report}")
    return True


