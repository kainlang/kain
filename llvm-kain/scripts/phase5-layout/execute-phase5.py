    with open(execute_log, "w") as f:
        f.write(f"Phase 5 Execute Log\n")
        f.write(f"==================\n")
        f.write(f"Date:             {datetime.now().isoformat()}\n")
        f.write(f"Duration:         {elapsed:.0f}s\n")
        f.write(f"Backup:           {backup_path}\n")
        f.write(f"Directories:      {created:,}\n")
        f.write(f"Files copied:     {copied:,}\n")
        f.write(f"Already existed:  {skipped:,}\n")
        f.write(f"Include fixes:    {include_fixes:,}\n")
        f.write(f"Empty dirs removed: {empty_removed:,}\n")
        f.write(f"Errors:           {total_errors}\n")
