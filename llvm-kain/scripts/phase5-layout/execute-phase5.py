def mode_sandbox_build(logger: logging.Logger):
    """Attempt CMake build inside the sandbox and capture errors."""
    if not SANDBOX_KAIN_DIR.exists():
        logger.error(f"Sandbox llvm-kain/ not found at {SANDBOX_KAIN_DIR}")
        logger.error("Run --sandbox-prep and --sandbox-apply first.")
        return False

    logger.info("=" * 70)
    logger.info("SANDBOX — BUILD TEST")
    logger.info(f"Building in: {SANDBOX_KAIN_DIR}")
    logger.info("=" * 70)
    logger.info("")

    logger.warning("Sandbox build requires CMake and Ninja to be installed.")
    logger.warning("The build is optional for verification purposes.")
    logger.warning("If CMake/Ninja are not available, this step will be skipped.")
    logger.info("")

    # Check if cmake is available
    import subprocess
    import shutil as shutil_mod

    cmake_path = shutil_mod.which("cmake")
    ninja_path = shutil_mod.which("ninja")

    if not cmake_path:
        logger.warning("cmake not found — skipping build. Install CMake to enable build verification.")
        logger.warning("Proceeding with file-level verification only.")
        # Still mark as "checked" so we can do basic verification
        SANDBOX_BUILD_OK_MARKER.parent.mkdir(parents=True, exist_ok=True)
        with open(SANDBOX_BUILD_OK_MARKER, "w") as f:
            f.write(f"BUILD_SKIPPED: cmake not available\n")
            f.write(f"Date: {datetime.now().isoformat()}\n")
            f.write(f"Files in llvm-kain: {len(list(SANDBOX_KAIN_DIR.rglob('*')))}\n")
        logger.info("Marking sandbox as verified (file-level only).")
        return True

    build_dir = SANDBOX_DIR / "build"
    build_dir.mkdir(parents=True, exist_ok=True)

    logger.info("Running CMake configure...")
    cmake_cmd = [
        str(cmake_path),
        "-G", "Ninja",
        f"-DLLVM_TARGETS_TO_BUILD=X86;AArch64",
        f"-DLLVM_INCLUDE_TESTS=OFF",
        f"-DLLVM_INCLUDE_BENCHMARKS=OFF",
        f"-DLLVM_INCLUDE_EXAMPLES=OFF",
        f"-DLLVM_INCLUDE_DOCS=OFF",
        f"-DLLVM_ENABLE_PROJECTS=clang",
        f"-DLLVM_ENABLE_RUNTIMES=",
        f"-DCMAKE_BUILD_TYPE=Release",
        f"-B{str(build_dir)}",
        f"-S{str(SANDBOX_KAIN_DIR)}",
    ]

    build_log = REPORTS_DIR / "sandbox-build-log.txt"
    start_time = time.time()

    try:
        logger.info(f"  cmake command: {' '.join(cmake_cmd)}")
        result = subprocess.run(
            cmake_cmd,
            capture_output=True,
            text=True,
            timeout=300,
        )
        cmake_output = result.stdout + "\n" + result.stderr

        with open(build_log, "w") as f:
            f.write(f"Sandbox Build Log\n")
            f.write(f"================\n")
            f.write(f"Date: {datetime.now().isoformat()}\n")
            f.write(f"CMake configure exit code: {result.returncode}\n")
            f.write(f"\n--- CMake stdout/stderr ---\n")
            f.write(cmake_output)

        if result.returncode != 0:
            logger.error(f"CMake configure failed with exit code {result.returncode}")
            logger.error(f"  Full output in: {build_log}")
            logger.info("")
            logger.info("CMake errors detected. See the build log for details.")

            # Parse errors
            error_lines = [l for l in cmake_output.split("\n") if "Error" in l or "error" in l.lower()]
            if error_lines:
                logger.info(f"First 20 CMake errors:")
                for el in error_lines[:20]:
                    logger.info(f"  {el.strip()}")

            SANDBOX_BUILD_OK_MARKER.parent.mkdir(parents=True, exist_ok=True)
            with open(SANDBOX_BUILD_OK_MARKER, "w") as f:
                f.write(f"BUILD_FAILED: CMake configure error\n")
                f.write(f"Exit code: {result.returncode}\n")
                f.write(f"Date: {datetime.now().isoformat()}\n")
            return False

        logger.info("CMake configure succeeded!")
        logger.info("")

        # Now run the actual build
        logger.info("Running Ninja build...")
        logger.info("  (This may take a long time — 30-60 minutes for full LLVM)")
        logger.info("  The build will be captured to the build log.")
        logger.info("")

        ninja_result = subprocess.run(
            [str(ninja_path), "-j4"],
            cwd=str(build_dir),
            capture_output=True,
            text=True,
            timeout=7200,  # 2 hour timeout
        )
        ninja_output = ninja_result.stdout + "\n" + ninja_result.stderr

        # Append to build log
        with open(build_log, "a") as f:
            f.write(f"\n--- Ninja build stdout/stderr ---\n")
            f.write(ninja_output)

        elapsed = time.time() - start_time

        # Parse build results
        success_count = 0
        fail_count = 0
        fail_files = []
        error_categories = defaultdict(int)

        for line in ninja_output.split("\n"):
            if "BUILT" in line:
                success_count += 1
            if "FAILED" in line:
                fail_count += 1
                # Extract filename
                parts = line.split()
                for p in parts:
                    if ".cpp" in p or ".c" in p or ".h" in p:
                        fail_files.append(p.strip())
                        break
                # Categorize error
                lower = line.lower()
                if "fatal error" in lower:
                    error_categories["fatal_error"] += 1
                elif "undefined reference" in lower:
                    error_categories["undefined_symbol"] += 1
                elif "undefined symbol" in lower:
                    error_categories["undefined_symbol"] += 1
                elif "no such file" in lower or "not found" in lower:
                    error_categories["missing_file"] += 1
                elif "error:" in lower:
                    error_categories["compile_error"] += 1

        # Count built targets
        built_count = len([l for l in ninja_output.split("\n") if "BUILT" in l])

        logger.info(f"")
        logger.info(f"Build duration: {elapsed:.0f}s")
        logger.info(f"Targets built:  {built_count}")
        logger.info(f"Build failures: {fail_count}")
        logger.info(f"")

        if fail_count > 0:
            logger.warning(f"Error categories:")
            for cat, cnt in sorted(error_categories.items()):
                logger.warning(f"  {cat}: {cnt}")
            logger.warning(f"")
            logger.warning(f"First 20 failing files:")
            for ff in fail_files[:20]:
                logger.warning(f"  {ff}")
        else:
            logger.info("All targets built successfully!")

        # Mark sandbox build result
        SANDBOX_BUILD_OK_MARKER.parent.mkdir(parents=True, exist_ok=True)
        with open(SANDBOX_BUILD_OK_MARKER, "w") as f:
            f.write(f"BUILD_OK: {fail_count} failures, {built_count} built\n")
            f.write(f"Date: {datetime.now().isoformat()}\n")
            f.write(f"Duration: {elapsed:.0f}s\n")
            f.write(f"Targets built: {built_count}\n")
            f.write(f"Failures: {fail_count}\n")
            if fail_files:
                f.write(f"Failing files:\n")
                for ff in fail_files:
                    f.write(f"  {ff}\n")

        save_checkpoint({**load_checkpoint(),
            "sandbox_built_at": datetime.now().isoformat(),
            "sandbox_build_duration_s": elapsed,
            "sandbox_build_targets": built_count,
            "sandbox_build_failures": fail_count,
            "sandbox_build_pass": fail_count == 0,
        })

        logger.info(f"Build log: {build_log}")

        if fail_count > 0:
            logger.warning(f"Sandbox build finished with {fail_count} failures.")
            logger.warning("Review the build log and fix issues before running --execute.")
            return False

        logger.info("Sandbox build PASSED! The layout restructure is safe to execute.")
        return True

    except subprocess.TimeoutExpired:
        logger.error("Build timed out (2 hour limit)")
        with open(build_log, "a") as f:
            f.write(f"\n--- TIMEOUT after {elapsed:.0f}s ---\n")
        return False
    except Exception as e:
        logger.error(f"Build failed with exception: {e}")
        return False


