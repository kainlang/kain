#!/usr/bin/env python3
"""Stub tablegen for llvm-kain -- creates empty .inc files.
Usage: stub-tablegen.py [options] -o output.inc [input.td]
"""
import sys
import os

output_file = None
for i, arg in enumerate(sys.argv[1:]):
    if arg == '-o' and i + 1 < len(sys.argv[1:]):
        output_file = sys.argv[i + 2]

if output_file is None:
    # Last positional arg might be the .td file, derive output from it
    for arg in reversed(sys.argv[1:]):
        if not arg.startswith('-'):
            output_file = os.path.splitext(arg)[0] + '.inc'
            break

if output_file is None:
    output_file = 'output.inc'

os.makedirs(os.path.dirname(output_file), exist_ok=True)
with open(output_file, 'w') as f:
    f.write('// Stub generated by llvm-kain stub-tablegen\n')
    f.write(f'// Original args: {" ".join(sys.argv[1:])}\n')
    f.write('#pragma once\n')
    f.write('#ifndef LLVM_KAIN_STUB_TABLEGEN\n')
    f.write('#define LLVM_KAIN_STUB_TABLEGEN\n')
    f.write('// Empty stub for stripped build\n')
    f.write('#endif\n')

sys.exit(0)
