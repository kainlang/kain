content.append("")
content.append("; kain_handle_slot: encoded = (uint32_t)(handle & 0xffffffff); return encoded-1 or UINT32_MAX if 0")
content.append("(define-fun encoded () (_ BitVec 32) ((_ extract 31 0) packed))")
content.append("(define-fun slot_out () (_ BitVec 32)")
content.append("  (ite (= encoded (_ bv0 32)) (_ bv4294967295 32) (bvsub encoded (_ bv1 32))))")
content.append("")
