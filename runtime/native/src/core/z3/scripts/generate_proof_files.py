content.append("(assert (bvult magic_raw (_ bv16777216 32)))")
content.append("")
content.append("; Pack: built exactly like kain_handle_make")
content.append("(define-fun packed () (_ BitVec 64)")
content.append("  (bvor")
content.append("    (bvshl ((_ zero_extend 56) kind) (_ bv56 64))")
content.append("    (bvshl ((_ zero_extend 32) ((_ extract 23 0) magic_raw)) (_ bv32 64))")
content.append("    (bvadd ((_ zero_extend 32) slot) (_ bv1 64))")
content.append("  ))")
content.append("")
content.append("; Extract: exactly like kain_handle_kind, kain_handle_slot, kain_handle_magic")
