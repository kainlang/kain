/// Generate a .uplugin file with correct module type(s) and loading phase(s)
pub fn generate_uplugin_file(plugin_name: &str, description: &Option<String>, has_editor_items: bool, needs_split: bool) -> String {
    let desc = description.as_ref()
        .map(|s| s.as_str())
        .unwrap_or("Generated by KAIN-PRO");
    
    let modules_json = if needs_split {
        // Two modules: Runtime + Editor
        format!(r#"    {{
      "Name": "{}",
      "Type": "Runtime",
      "LoadingPhase": "PostConfigInit"
    }},
    {{
      "Name": "{}Editor",
      "Type": "Editor",
      "LoadingPhase": "PostEngineInit"
    }}"#, plugin_name, plugin_name)
    } else {
        // Single module
        let (module_type, loading_phase) = if has_editor_items {
            ("Editor", "PostEngineInit")
        } else {
            ("Runtime", "PostConfigInit")
        };
        format!(r#"    {{
      "Name": "{}",
      "Type": "{}",
      "LoadingPhase": "{}"
    }}"#, plugin_name, module_type, loading_phase)
    };
    
    format!(r#"{{
  "FileVersion": 3,
  "Version": 1,
  "VersionName": "1.0.0",
  "FriendlyName": "{}",
  "Description": "{}",
  "Category": "KAIN-PRO",
  "CreatedBy": "KAIN-PRO Compiler",
  "CreatedByURL": "",
  "DocsURL": "",
  "MarketplaceURL": "",
  "SupportURL": "",
  "CanContainContent": false,
  "IsBetaVersion": false,
  "IsExperimentalVersion": false,
  "Installed": false,
  "Modules": [
{}
  ]
}}
"#, plugin_name, desc, modules_json)
}
