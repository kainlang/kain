use std::collections::BTreeSet;

/// Format a sorted set of module names as C# string array entries (indented with tabs).
fn format_dep_list(deps: &BTreeSet<String>, indent: &str) -> String {
    deps.iter()
        .map(|d| format!("{}\"{}\"", indent, d))
        .collect::<Vec<_>>()
        .join(",\n")
}

/// Generate a .Build.cs file for the UE5 plugin module (single-module mode).
/// `extra_public_deps` and `extra_private_deps` are resolved from the module graph.
pub fn generate_build_cs(
    plugin_name: &str,
    has_editor_items: bool,
    extra_public_deps: &[String],
    extra_private_deps: &[String],
) -> String {
    // Base public deps (always needed)
    let mut public_deps: BTreeSet<String> = ["Core", "CoreUObject", "Engine", "Projects"]
        .iter().map(|s| s.to_string()).collect();
    for dep in extra_public_deps {
        public_deps.insert(dep.clone());
    }

    // Private deps
    let mut private_deps: BTreeSet<String> = BTreeSet::new();
    for dep in extra_private_deps {
        private_deps.insert(dep.clone());
    }

    if has_editor_items {
        for dep in &["Slate", "SlateCore", "UnrealEd", "AssetTools", "EditorStyle", "PropertyEditor", "InputCore"] {
            private_deps.insert(dep.to_string());
        }
    }

    let public_list = format_dep_list(&public_deps, "\t\t\t\t");
    let private_list = format_dep_list(&private_deps, "\t\t\t\t");

    let include_paths = if has_editor_items {
        r#"
		PublicIncludePaths.AddRange(
			new string[] {
				System.IO.Path.Combine(ModuleDirectory, "Public/Editor")
			}
		);
				
		PrivateIncludePaths.AddRange(
			new string[] {
				System.IO.Path.Combine(ModuleDirectory, "Private/Editor")
			}
		);"#
    } else {
        ""
    };

    format!(r#"// Generated by KAIN-PRO Compiler
using UnrealBuildTool;
using System.IO;

public class {name} : ModuleRules
{{
	public {name}(ReadOnlyTargetRules Target) : base(Target)
	{{
		PCHUsage = ModuleRules.PCHUsageMode.UseExplicitOrSharedPCHs;
		{include_paths}
		PublicDependencyModuleNames.AddRange(
			new string[]
			{{
{public_list}
			}}
		);

		PrivateDependencyModuleNames.AddRange(
			new string[]
			{{
{private_list}
			}}
		);
	}}
}}
"#, name = plugin_name, include_paths = include_paths,
    public_list = public_list, private_list = private_list)
}


/// Generate a .Build.cs for the RUNTIME module in split mode.
/// `extra_public_deps` are resolved from the module graph based on referenced types/APIs.
pub fn generate_build_cs_runtime(plugin_name: &str, extra_public_deps: &[String]) -> String {
    let mut public_deps: BTreeSet<String> = ["Core", "CoreUObject", "Engine", "Projects"]
        .iter().map(|s| s.to_string()).collect();
    for dep in extra_public_deps {
        public_deps.insert(dep.clone());
    }

    let public_list = format_dep_list(&public_deps, "\t\t\t\t");

    format!(r#"// Generated by KAIN-PRO Compiler — Runtime Module
using UnrealBuildTool;
using System.IO;

public class {name} : ModuleRules
{{
	public {name}(ReadOnlyTargetRules Target) : base(Target)
	{{
		PCHUsage = ModuleRules.PCHUsageMode.UseExplicitOrSharedPCHs;

		PublicDependencyModuleNames.AddRange(
			new string[]
			{{
{public_list}
			}}
		);
	}}
}}
"#, name = plugin_name, public_list = public_list)
}

/// Generate a .Build.cs for the EDITOR module in split mode.
/// `extra_public_deps` and `extra_private_deps` are resolved from the module graph.
pub fn generate_build_cs_editor(
    plugin_name: &str,
    extra_public_deps: &[String],
    extra_private_deps: &[String],
) -> String {
    let editor_module_name = format!("{}Editor", plugin_name);

    // Editor always depends on its runtime module
    let mut public_deps: BTreeSet<String> = ["Core", "CoreUObject", "Engine"]
        .iter().map(|s| s.to_string()).collect();
    public_deps.insert(plugin_name.to_string());
    for dep in extra_public_deps {
        public_deps.insert(dep.clone());
    }

    // Standard editor private deps
    let mut private_deps: BTreeSet<String> = [
        "Slate", "SlateCore", "UnrealEd", "AssetTools",
        "EditorStyle", "PropertyEditor", "InputCore", "Projects",
    ].iter().map(|s| s.to_string()).collect();
    for dep in extra_private_deps {
        private_deps.insert(dep.clone());
    }

    let public_list = format_dep_list(&public_deps, "\t\t\t\t");
    let private_list = format_dep_list(&private_deps, "\t\t\t\t");

    format!(r#"// Generated by KAIN-PRO Compiler — Editor Module
using UnrealBuildTool;
using System.IO;

public class {name} : ModuleRules
{{
	public {name}(ReadOnlyTargetRules Target) : base(Target)
	{{
		PCHUsage = ModuleRules.PCHUsageMode.UseExplicitOrSharedPCHs;

		PublicDependencyModuleNames.AddRange(
			new string[]
			{{
{public_list}
			}}
		);

		PrivateDependencyModuleNames.AddRange(
			new string[]
			{{
{private_list}
			}}
		);
	}}
}}
"#, name = editor_module_name, public_list = public_list, private_list = private_list)
}
