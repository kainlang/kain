/// Format a sorted set of module names as C# string array entries (indented with tabs).
fn format_dep_list(deps: &BTreeSet<String>, indent: &str) -> String {
    deps.iter()
        .map(|d| format!("{}\"{}\"", indent, d))
        .collect::<Vec<_>>()
        .join(",\n")
}

/// Generate a generic .Build.cs for an explicitly configured module.
///
/// This is used by the data-driven multi-module mode and keeps legacy
/// single/split generators untouched.
pub fn generate_build_cs_module(
    module_name: &str,
    public_deps: &[String],
    private_deps: &[String],
) -> String {
    let mut public: BTreeSet<String> = BTreeSet::new();
    let mut private: BTreeSet<String> = BTreeSet::new();

    for dep in public_deps {
        public.insert(dep.clone());
    }
    for dep in private_deps {
        private.insert(dep.clone());
    }

    let public_list = format_dep_list(&public, "\t\t\t\t");
    let private_list = format_dep_list(&private, "\t\t\t\t");

    format!(
        r#"// Generated by KAIN-PRO Compiler — Data-Driven Module
using UnrealBuildTool;
using System.IO;

public class {name} : ModuleRules
{{
	public {name}(ReadOnlyTargetRules Target) : base(Target)
	{{
		PCHUsage = ModuleRules.PCHUsageMode.UseExplicitOrSharedPCHs;

		PublicDependencyModuleNames.AddRange(
			new string[]
			{{
{public_list}
			}}
		);

		PrivateDependencyModuleNames.AddRange(
			new string[]
			{{
{private_list}
			}}
		);
	}}
}}
"#,
        name = module_name,
        public_list = public_list,
        private_list = private_list
    )
}

/// Generate a .Build.cs file for the UE5 plugin module (single-module mode).
/// `extra_public_deps` and `extra_private_deps` are resolved from the module graph.
pub fn generate_build_cs(
    plugin_name: &str,
    has_editor_items: bool,
    extra_public_deps: &[String],
    extra_private_deps: &[String],
) -> String {
    // Base public deps (always needed)
    let mut public_deps: BTreeSet<String> = ["Core", "CoreUObject", "Engine", "Projects"]
        .iter()
        .map(|s| s.to_string())
        .collect();
    for dep in extra_public_deps {
        public_deps.insert(dep.clone());
    }

    // Private deps
    let mut private_deps: BTreeSet<String> = BTreeSet::new();
    for dep in extra_private_deps {
        private_deps.insert(dep.clone());
    }

    if has_editor_items {
        for dep in &[
            "Slate",
            "SlateCore",
            "UnrealEd",
            "AssetTools",
            "EditorStyle",
            "PropertyEditor",
            "InputCore",
        ] {
            private_deps.insert(dep.to_string());
        }
    }

    let public_list = format_dep_list(&public_deps, "\t\t\t\t");
    let private_list = format_dep_list(&private_deps, "\t\t\t\t");

    let include_paths = if has_editor_items {
        r#"
		PublicIncludePaths.AddRange(
			new string[] {
				System.IO.Path.Combine(ModuleDirectory, "Public/Editor")
			}
		);
				
		PrivateIncludePaths.AddRange(
			new string[] {
				System.IO.Path.Combine(ModuleDirectory, "Private/Editor")
			}
		);"#
    } else {
        ""
    };

    format!(
        r#"// Generated by KAIN-PRO Compiler
using UnrealBuildTool;
using System.IO;

public class {name} : ModuleRules
{{
	public {name}(ReadOnlyTargetRules Target) : base(Target)
	{{
		PCHUsage = ModuleRules.PCHUsageMode.UseExplicitOrSharedPCHs;
		{include_paths}
		PublicDependencyModuleNames.AddRange(
			new string[]
			{{
{public_list}
			}}
		);

		PrivateDependencyModuleNames.AddRange(
			new string[]
			{{
{private_list}
			}}
		);
	}}
}}
"#,
        name = plugin_name,
        include_paths = include_paths,
        public_list = public_list,
        private_list = private_list
    )
}

