/// C++ Blueprint factory generator.
///
/// Generates a `UBlueprintFactory`-based C++ module that creates Blueprint assets
/// at editor startup — same proven pattern as `ue5-materials` material factory.
///
/// This is Phase 1: works with any UE5 version, no binary format knowledge needed.
/// Phase 2 (BlueprintBinaryWriter) will write .uasset bytes directly.
use crate::ir::{
    BlueprintDef, ComponentDef, EventGraphNode, KismetCall, PropertyDef, PropertyValue,
};

pub struct BlueprintFactoryGenerator;

impl BlueprintFactoryGenerator {
    /// Generate the complete C++ factory header for a blueprint definition.
    pub fn generate_header(bp: &BlueprintDef) -> String {
        let class_name = factory_class_name(&bp.name);
        format!(
            r#"#pragma once

#include "CoreMinimal.h"
#include "Modules/ModuleManager.h"
#include "Kismet2/KismetEditorUtilities.h"
#include "Kismet2/BlueprintEditorUtils.h"
#include "Engine/SimpleConstructionScript.h"
#include "Engine/SCS_Node.h"

/**
 * KAIN-generated Blueprint factory for {name}
 * Parent class: {parent}
 * Generated by: ue5-blueprints crate
 *
 * DO NOT EDIT — regenerate via `kain build --ue5`
 */
class {class_name}
{{
public:
    /** Create and register the {name} Blueprint asset. Call from module StartupModule(). */
    static void Create(UObject* Outer = nullptr);

private:
    static void SetupComponents(UBlueprint* Blueprint);
    static void SetupDefaults(UBlueprint* Blueprint);
    static void SetupEventGraph(UBlueprint* Blueprint);
}};
"#,
            name = bp.name,
            parent = bp.parent_class,
            class_name = class_name,
        )
    }

    /// Generate the complete C++ factory implementation for a blueprint definition.
    pub fn generate_source(bp: &BlueprintDef) -> String {
        let class_name = factory_class_name(&bp.name);
        let package_path = &bp.package_path;
        let bp_name = &bp.name;
        let parent_class = parent_cpp_class(&bp.parent_class);

        let component_setup = Self::generate_component_setup(&bp.components);
        let defaults_setup = Self::generate_defaults_setup(&bp.defaults, "BlueprintCDO");
        let event_graph_setup = Self::generate_event_graph(&bp.event_graph);

        format!(
            r#"#include "{class_name}.h"
#include "AssetRegistry/AssetRegistryModule.h"
#include "UObject/Package.h"
#include "UObject/SavePackage.h"
#include "EdGraph/EdGraph.h"
#include "K2Node_Event.h"
#include "K2Node_CallFunction.h"
#include "EdGraphSchema_K2.h"

void {class_name}::Create(UObject* Outer)
{{
    // ── Package ───────────────────────────────────────────────────────────────
    const FString PackagePath = TEXT("{package_path}/{bp_name}");
    UPackage* Package = CreatePackage(*PackagePath);
    Package->FullyLoad();

    // Skip if already exists
    if (UBlueprint* Existing = Cast<UBlueprint>(
            StaticFindObject(UBlueprint::StaticClass(), Package, TEXT("{bp_name}"))))
    {{
        return;
    }}

    // ── Blueprint ─────────────────────────────────────────────────────────────
    UBlueprint* Blueprint = FKismetEditorUtilities::CreateBlueprint(
        {parent_class}::StaticClass(),
        Package,
        FName(TEXT("{bp_name}")),
        BPTYPE_Normal,
        UBlueprint::StaticClass(),
        UBlueprintGeneratedClass::StaticClass()
    );

    if (!Blueprint)
    {{
        UE_LOG(LogTemp, Error, TEXT("KAIN: Failed to create Blueprint {bp_name}"));
        return;
    }}

    // ── Components, Defaults, Event Graph ────────────────────────────────────
    SetupComponents(Blueprint);
    SetupDefaults(Blueprint);
    SetupEventGraph(Blueprint);

    // ── Compile & Save ────────────────────────────────────────────────────────
    FKismetEditorUtilities::CompileBlueprint(Blueprint);

    Package->MarkPackageDirty();
    FAssetRegistryModule::AssetCreated(Blueprint);

    FSavePackageArgs SaveArgs;
    SaveArgs.TopLevelFlags = RF_Public | RF_Standalone;
    UPackage::SavePackage(Package, Blueprint,
        *(PackagePath + TEXT(".uasset")), SaveArgs);

    UE_LOG(LogTemp, Log, TEXT("KAIN: Created Blueprint %s"), TEXT("{bp_name}"));
}}

{component_setup}

{defaults_setup}

{event_graph_setup}
"#,
            class_name = class_name,
            package_path = package_path,
            bp_name = bp_name,
            parent_class = parent_class,
            component_setup = component_setup,
            defaults_setup = defaults_setup,
            event_graph_setup = event_graph_setup,
        )
    }

    // ── Component Setup ───────────────────────────────────────────────────────

    fn generate_component_setup(components: &[ComponentDef]) -> String {
        if components.is_empty() {
            return format!(
                "void PLACEHOLDER::SetupComponents(UBlueprint* Blueprint) {{ /* no components */ }}"
            );
        }

        let mut lines = Vec::new();
        lines.push(
            "    USimpleConstructionScript* SCS = Blueprint->SimpleConstructionScript;".to_string(),
        );
        lines.push("    if (!SCS) return;".to_string());
        lines.push(String::new());

        for (i, comp) in components.iter().enumerate() {
            let node_var = format!("Node_{}", i);
            let class_name = &comp.class_name;
            let var_name = &comp.variable_name;

            lines.push(format!("    // Component: {var_name} ({class_name})"));
            lines.push(format!(
                "    USCS_Node* {node_var} = SCS->CreateNodeWithoutOwner(U{class_name}::StaticClass(), FName(TEXT(\"{var_name}\")));"
            ));

            // Attach to parent or root
            if let Some(parent) = &comp.attach_parent {
                lines.push(format!("    // Attach {var_name} to parent: {parent}"));
                lines.push(format!(
                    "    {{ USCS_Node* ParentNode = SCS->FindSCSNode(FName(TEXT(\"{parent}\"))); if (ParentNode) ParentNode->ChildNodes.Add({node_var}); }}"
                ));
            } else {
                lines.push(format!("    SCS->AddNode({node_var});"));
            }

            // Component defaults
            if !comp.defaults.is_empty() {
                lines.push(format!(
                    "    U{class_name}* {node_var}_CDO = Cast<U{class_name}>({node_var}->ComponentTemplate);"
                ));
                lines.push(format!("    if ({node_var}_CDO)"));
                lines.push("    {".to_string());
                for prop in &comp.defaults {
                    if let Some(setter) = property_setter(prop, &format!("{node_var}_CDO")) {
                        lines.push(format!("        {setter}"));
                    }
                }
                lines.push("    }".to_string());
            }
            lines.push(String::new());
        }

        format!(
            "void PLACEHOLDER::SetupComponents(UBlueprint* Blueprint)\n{{\n{}\n}}",
            lines.join("\n")
        )
    }

    // ── CDO Defaults ─────────────────────────────────────────────────────────

    fn generate_defaults_setup(defaults: &[PropertyDef], cdo_var: &str) -> String {
        if defaults.is_empty() {
            return format!(
                "void PLACEHOLDER::SetupDefaults(UBlueprint* Blueprint) {{ /* no defaults */ }}"
            );
        }

        let mut lines = Vec::new();
        lines.push(format!(
            "    auto* {cdo_var} = Cast<AActor>(Blueprint->GeneratedClass->GetDefaultObject(true));"
        ));
        lines.push(format!("    if (!{cdo_var}) return;"));
        lines.push(String::new());

        for prop in defaults {
            if let Some(setter) = property_setter(prop, cdo_var) {
                lines.push(format!("    {setter}"));
            }
        }

        format!(
            "void PLACEHOLDER::SetupDefaults(UBlueprint* Blueprint)\n{{\n{}\n}}",
            lines.join("\n")
        )
    }

    // ── Event Graph ───────────────────────────────────────────────────────────

    fn generate_event_graph(events: &[EventGraphNode]) -> String {
        if events.is_empty() {
            return format!(
                "void PLACEHOLDER::SetupEventGraph(UBlueprint* Blueprint) {{ /* no event graph */ }}"
            );
        }

        let mut lines = Vec::new();
        lines.push(
            "    UEdGraph* EventGraph = FBlueprintEditorUtils::FindEventGraph(Blueprint);"
                .to_string(),
        );
        lines.push("    if (!EventGraph) return;".to_string());
        lines.push(String::new());

        for (i, event) in events.iter().enumerate() {
            match event {
                EventGraphNode::BeginPlay { calls } => {
                    lines.push(format!("    // Event BeginPlay (node group {})", i));
                    lines.push("    {".to_string());
                    lines.push(
                        "        UK2Node_Event* EventNode = NewObject<UK2Node_Event>(EventGraph);"
                            .to_string(),
                    );
                    lines.push("        EventNode->EventReference.SetExternalMember(FName(\"ReceiveBeginPlay\"), AActor::StaticClass());".to_string());
                    lines.push("        EventNode->bOverrideFunction = true;".to_string());
                    lines.push("        EventGraph->AddNode(EventNode, false, false);".to_string());
                    lines.push(generate_call_chain(calls, "EventNode"));
                    lines.push("    }".to_string());
                }
                EventGraphNode::Tick { calls } => {
                    lines.push(format!("    // Event Tick (node group {})", i));
                    lines.push("    {".to_string());
                    lines.push(
                        "        UK2Node_Event* TickNode = NewObject<UK2Node_Event>(EventGraph);"
                            .to_string(),
                    );
                    lines.push("        TickNode->EventReference.SetExternalMember(FName(\"ReceiveTick\"), AActor::StaticClass());".to_string());
                    lines.push("        TickNode->bOverrideFunction = true;".to_string());
                    lines.push("        EventGraph->AddNode(TickNode, false, false);".to_string());
                    lines.push(generate_call_chain(calls, "TickNode"));
                    lines.push("    }".to_string());
                }
                EventGraphNode::CustomEvent { event_name, calls } => {
                    lines.push(format!(
                        "    // Custom Event: {event_name} (node group {i})"
                    ));
                    lines.push("    {".to_string());
                    lines.push("        UK2Node_CustomEvent* CustomNode = NewObject<UK2Node_CustomEvent>(EventGraph);".to_string());
                    lines.push(format!(
                        "        CustomNode->CustomFunctionName = FName(TEXT(\"{event_name}\"));"
                    ));
                    lines
                        .push("        EventGraph->AddNode(CustomNode, false, false);".to_string());
                    lines.push(generate_call_chain(calls, "CustomNode"));
                    lines.push("    }".to_string());
                }
            }
            lines.push(String::new());
        }

        lines.push(
            "    FBlueprintEditorUtils::MarkBlueprintAsStructurallyModified(Blueprint);"
                .to_string(),
        );

        format!(
            "void PLACEHOLDER::SetupEventGraph(UBlueprint* Blueprint)\n{{\n{}\n}}",
            lines.join("\n")
        )
    }
}

// ── Helpers ───────────────────────────────────────────────────────────────────

fn factory_class_name(bp_name: &str) -> String {
    format!("F{}Factory", bp_name)
}

/// Extract the C++ class name from a script path like "/Script/MyPlugin.APlayerBase"
fn parent_cpp_class(parent_class: &str) -> &str {
    parent_class.split('.').last().unwrap_or(parent_class)
}

/// Generate a C++ setter expression for a property
fn property_setter(prop: &PropertyDef, obj: &str) -> Option<String> {
    match &prop.value {
        PropertyValue::Bool(v) => Some(format!("{}->{}  = {};", obj, prop.name, v)),
        PropertyValue::Int(v) => Some(format!("{}->{}  = {};", obj, prop.name, v)),
        PropertyValue::Float(v) => Some(format!("{}->{}  = {}f;", obj, prop.name, v)),
        PropertyValue::Double(v) => Some(format!("{}->{}  = {};", obj, prop.name, v)),
        PropertyValue::Str(v) => Some(format!("{}->{}  = TEXT(\"{}\");", obj, prop.name, v)),
        PropertyValue::Name(v) => {
            Some(format!("{}->{}  = FName(TEXT(\"{}\"));", obj, prop.name, v))
        }
        PropertyValue::SoftObject(path) => Some(format!(
            "{}->{}  = FSoftObjectPath(TEXT(\"{}\"));",
            obj, prop.name, path
        )),
        PropertyValue::Vector { x, y, z } => Some(format!(
            "{}->{}  = FVector({}f, {}f, {}f);",
            obj, prop.name, x, y, z
        )),
        PropertyValue::Rotator { pitch, yaw, roll } => Some(format!(
            "{}->{}  = FRotator({}f, {}f, {}f);",
            obj, prop.name, pitch, yaw, roll
        )),
        PropertyValue::LinearColor { r, g, b, a } => Some(format!(
            "{}->{}  = FLinearColor({}f, {}f, {}f, {}f);",
            obj, prop.name, r, g, b, a
        )),
        PropertyValue::Enum { enum_type, value } => Some(format!(
            "{}->{}  = {}::{};",
            obj, prop.name, enum_type, value
        )),
        PropertyValue::Text(v) => Some(format!(
            "{}->{}  = FText::FromString(TEXT(\"{}\"));",
            obj, prop.name, v
        )),
        // Complex types — skip for now, handled by binary writer
        _ => None,
    }
}

/// Generate a chain of UK2Node_CallFunction nodes connected by exec pins
fn generate_call_chain(calls: &[KismetCall], entry_node: &str) -> String {
    if calls.is_empty() {
        return String::new();
    }

    let mut lines = Vec::new();
    lines.push(format!(
        "        UEdGraphPin* PrevThen = {}->FindPin(UEdGraphSchema_K2::PN_Then);",
        entry_node
    ));

    for (i, call) in calls.iter().enumerate() {
        let node_var = format!("CallNode_{}", i);
        lines.push(format!(
            "        UK2Node_CallFunction* {node_var} = NewObject<UK2Node_CallFunction>(EventGraph);"
        ));
        lines.push(format!(
            "        {node_var}->FunctionReference.SetExternalMember(FName(TEXT(\"{}\")), Blueprint->GeneratedClass);",
            call.function_name
        ));
        lines.push(format!(
            "        EventGraph->AddNode({node_var}, false, false);"
        ));
        lines.push(format!(
            "        if (PrevThen) PrevThen->MakeLinkTo({node_var}->FindPin(UEdGraphSchema_K2::PN_Execute));"
        ));
        lines.push(format!(
            "        PrevThen = {node_var}->FindPin(UEdGraphSchema_K2::PN_Then);"
        ));
    }

    lines.join("\n")
}
