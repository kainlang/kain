/// Public wrapper around the internal struct-to-HLSL-type map builder.
/// Used by the material graph converter to seed the type database for
/// [`emit_shader_body`] when performing the shader→CustomHLSL bridge.
pub fn build_struct_map_pub(program: &TypedProgram) -> HashMap<String, HashMap<String, String>> {
    build_struct_map(program)
}

fn build_struct_map(program: &TypedProgram) -> HashMap<String, HashMap<String, String>> {
    let mut type_db: HashMap<String, HashMap<String, String>> = HashMap::new();
    for item in &program.items {
        match item {
            TypedItem::Struct(s) => {
                let mut fields = HashMap::new();
                for f in &s.ast.fields {
                    if let Some(mapped) = try_map_type_to_usf_silent(&f.ty) {
                        fields.insert(f.name.clone(), mapped);
                    }
                }
                type_db.insert(s.ast.name.clone(), fields);
            }
            TypedItem::Component(c) => {
                let mut props = HashMap::new();
                for p in &c.ast.props {
                    if let Some(mapped) = try_map_type_to_usf_silent(&p.ty) {
                        props.insert(p.name.clone(), mapped);
                    }
                }
                type_db.insert(c.ast.name.clone(), props.clone());
                type_db.insert(format!("F{}ComponentData", c.ast.name), props);
            }
            TypedItem::Actor(a) => {
                let mut state = HashMap::new();
                for s in &a.ast.state {
                    if let Some(mapped) = try_map_type_to_usf_silent(&s.ty) {
                        state.insert(s.name.clone(), mapped);
                    }
                }
                type_db.insert(a.ast.name.clone(), state);
            }
            _ => {}
        }
    }
    type_db
}

fn is_hlsl_swizzle(s: &str) -> bool {
    if s.is_empty() || s.len() > 4 {
        return false;
    }
    let valid_xyzw = s.chars().all(|c| "xyzw".contains(c));
    let valid_rgba = s.chars().all(|c| "rgba".contains(c));
    valid_xyzw || valid_rgba
}

fn infer_field_type(ctx: &USFContext, obj_type: &str, field_name: &str) -> String {
    if is_hlsl_swizzle(field_name) {
        return infer_swizzle_type(field_name);
    }

    if let Some(fields) = ctx.struct_map.get(obj_type) {
        if let Some(ty) = fields.get(field_name) {
            return ty.clone();
        }
    }

    // Fallback to float
    "float".to_string()
}

/// Determine whether a compute shader operates on 3D volume data.
///
/// The heuristic checks for explicit `Image3D` or `RWTexture3D` uniforms — if
/// the shader writes to a 3D texture it is a 3D compute shader.  The dispatch
/// ID type (always `uint3` / `Vec3` regardless of dimensionality) is
/// intentionally **not** used as the signal.
fn is_3d_compute_shader(shader: &TypedShader) -> bool {
    shader.ast.uniforms.iter().any(|u| {
        let usf_ty = map_type_to_usf(&u.ty);
        usf_ty.contains("RWTexture3D") || usf_ty.contains("Texture3D")
    })
}
