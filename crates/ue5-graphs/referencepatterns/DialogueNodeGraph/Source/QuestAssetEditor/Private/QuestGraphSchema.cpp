UEdGraphNode* FNewCommentNodeAction::PerformAction(UEdGraph* parentGraph, UEdGraphPin* fromPin,
    const FVector2D location, bool bSelectNewNode)
{
    // Get asset info from graph context menu builder object.
    UQuestAsset * asset = Cast<UQuestAsset>(parentGraph->GetTypedOuter(UQuestAsset::StaticClass()));
    UEdGraphNode_Comment * CommentNode = NewObject<UEdGraphNode_Comment>();
    QuestAssetEditorApp * editor = nullptr;
    FVector2D _location = location;
    
    if(asset != nullptr)
    {
        // Search the editor to get bounds of the selected nodes :
        UAssetEditorSubsystem* AssetEditorSubsystem = GEditor->GetEditorSubsystem<UAssetEditorSubsystem>();
        if(AssetEditorSubsystem != nullptr)
        {
            editor = static_cast<QuestAssetEditorApp*>(AssetEditorSubsystem->FindEditorForAsset(asset, false));
        }

        if(editor != nullptr)
        {
            FSlateRect bounds;
            if(editor->GetBoundsOfSelection(bounds, 50))
            {
                CommentNode->SetBounds(bounds);
                _location.X = CommentNode->NodePosX;
                _location.Y = CommentNode->NodePosY;
            }
            else
            {
                CommentNode->SetBounds(FSlateRect(_location.X, _location.Y, _location.X + 200, _location.Y + 100));
            }
        }
    }

    UEdGraphNode* NewNode = FEdGraphSchemaAction_NewNode::SpawnNodeFromTemplate<UEdGraphNode_Comment>(parentGraph, CommentNode, _location, bSelectNewNode);
    
    return NewNode;
}
