UEdGraphNode* FNewQuestNodeAction::PerformAction(UEdGraph* parentGraph, UEdGraphPin* fromPin, const FVector2D location, bool bSelectNewNode) {
    UQuestGraphNodeBase* result = NewObject<UQuestGraphNodeBase>(parentGraph, _classTemplate);
    result->CreateNewGuid();
    result->NodePosX = location.X;
    result->NodePosY = location.Y;
    result->InitNodeInfo(result);
    result->UpdateIDToBeUnique();
    
    UEdGraphPin* inputPin = result->CreateDefaultInputPin();
    result->CreateDefaultOutputPins();

    if (fromPin != nullptr) {
        result->GetSchema()->TryCreateConnection(fromPin, inputPin);
    }

    if(AutoFillTaskClass != nullptr && result->GetNodeInfo()->IsA<UQuestTaskListNodeInfo>())
    {
        UQuestTaskListNodeInfo * nodeInfo = Cast<UQuestTaskListNodeInfo>(result->GetNodeInfo());
        UDialogueMasterTask * task = NewObject<UDialogueMasterTask>(nodeInfo, AutoFillTaskClass);
        nodeInfo->Tasks.Add(task);
    }

    if(AutoFillTaskClass == nullptr && result->GetNodeInfo()->IsA<UQuestStepNodeInfo>())
    {
        UQuestStepNodeInfo * nodeInfo = Cast<UQuestStepNodeInfo>(result->GetNodeInfo());
        nodeInfo->StepType = stepType;

        if(stepType == QUEST_SUCCEEDED || stepType == QUEST_FAILED)
        {
            nodeInfo->NodeOutputs.Empty();
            result->OnPropertiesChanged();
        }
    }
    
    parentGraph->Modify();
    parentGraph->AddNode(result, true, true);
    
    return result;
}


