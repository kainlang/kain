//! NodeData Class Generator
//!
//! Generates runtime NodeData classes for graph execution.
//!
//! Pattern:
//! ```cpp
//! // Base class
//! UCLASS()
//! class U{Name}GraphNodeData : public UObject {
//!     GENERATED_BODY()
//! public:
//!     UPROPERTY()
//!     TArray<U{Name}PinData*> InputPins;
//!     
//!     UPROPERTY()
//!     TArray<U{Name}PinData*> OutputPins;
//!     
//!     UPROPERTY()
//!     FIntPoint NodePosition;
//!     
//!     UPROPERTY()
//!     FGuid NodeGuid;
//!     
//!     U{Name}GraphNodeData* GetNextOutputNodeByPinIndex(int OutputPinIndex) const;
//!     virtual const U{Name}GraphNodeData* ExecuteNode(U{Name}GraphInstance* Instance) const;
//! };
//!
//! // Subclass
//! UCLASS()
//! class U{NodeType}NodeData : public U{Name}GraphNodeData {
//!     GENERATED_BODY()
//! public:
//!     // Properties from @property
//!     UPROPERTY(EditAnywhere, BlueprintReadOnly, Category = "Node Data")
//!     FString SomeProperty;
//!     
//!     virtual const U{Name}GraphNodeData* ExecuteNode(U{Name}GraphInstance* Instance) const override;
//! };
//! ```

use crate::{GraphEditor, NodeType, PinType, Result};

/// Output structure for NodeData generation
#[derive(Debug, Clone)]
pub struct NodeDataOutput {
    /// Base NodeData class header (filename, content)
    pub base_header: (String, String),
    /// Base NodeData class source (filename, content)
    pub base_source: (String, String),
    /// PinData class header (filename, content)
    pub pin_data_header: (String, String),
    /// PinData class source (filename, content)
    pub pin_data_source: (String, String),
    /// NodeData subclass headers (filename, content)
    pub node_data_headers: Vec<(String, String)>,
    /// NodeData subclass sources (filename, content)
    pub node_data_sources: Vec<(String, String)>,
}

pub struct NodeDataGenerator {
    plugin_name: String,
    graph: GraphEditor,
}

impl NodeDataGenerator {
    /// Create a new NodeData generator
    pub fn new(graph: &GraphEditor, plugin_name: impl Into<String>) -> Self {
        Self {
            plugin_name: plugin_name.into(),
            graph: graph.clone(),
        }
    }

    /// Generate complete NodeData output
    pub fn generate(&self) -> Result<NodeDataOutput> {
        let mut node_data_headers = Vec::new();
        let mut node_data_sources = Vec::new();

        // Generate PinData class
        let pin_data_header = self.generate_pin_data_header()?;
        let pin_data_source = self.generate_pin_data_source()?;

        // Generate base NodeData class
        let base_header = self.generate_base_node_data_header()?;
        let base_source = self.generate_base_node_data_source()?;

        // Generate NodeData subclasses
        for node_type in &self.graph.node_types {
            let (header, source) = self.generate_node_data_subclass(node_type)?;
            let class_name = format!("{}NodeData", node_type.name);
            node_data_headers.push((format!("{}.h", class_name), header));
            node_data_sources.push((format!("{}.cpp", class_name), source));
        }

        Ok(NodeDataOutput {
            base_header: (format!("{}GraphNodeData.h", self.graph.name), base_header),
            base_source: (format!("{}GraphNodeData.cpp", self.graph.name), base_source),
            pin_data_header: (format!("{}PinData.h", self.graph.name), pin_data_header),
            pin_data_source: (format!("{}PinData.cpp", self.graph.name), pin_data_source),
            node_data_headers,
            node_data_sources,
        })
    }

    /// Generate PinData class header
    pub fn generate_pin_data_header(&self) -> Result<String> {
        let class_name = format!("U{}PinData", self.graph.name);
        let api_macro = format!("{}_API", self.plugin_name.to_uppercase());

        let mut lines = Vec::new();

        lines.push("// Generated by KAIN compiler".to_string());
        lines.push(String::new());
        lines.push("#pragma once".to_string());
        lines.push(String::new());
        lines.push("#include \"CoreMinimal.h\"".to_string());
        lines.push("#include \"UObject/NoExportTypes.h\"".to_string());
        lines.push(format!(
            "#include \"{}PinData.generated.h\"",
            self.graph.name
        ));
        lines.push(String::new());

        lines.push(format!(
            "class {};",
            format!("U{}GraphNodeData", self.graph.name)
        ));
        lines.push(String::new());

        lines.push("UCLASS()".to_string());
        lines.push(format!("class {} {}", api_macro, class_name));
        lines.push("\t: public UObject".to_string());
        lines.push("{".to_string());
        lines.push("\tGENERATED_BODY()".to_string());
        lines.push(String::new());
        lines.push("public:".to_string());

        // Pin name
        lines.push("\tUPROPERTY()".to_string());
        lines.push("\tFName PinName;".to_string());
        lines.push(String::new());

        // Pin ID
        lines.push("\tUPROPERTY()".to_string());
        lines.push("\tFGuid PinId;".to_string());
        lines.push(String::new());

        // Connected pins
        lines.push("\tUPROPERTY()".to_string());
        lines.push(format!("\tTArray<{}*> ConnectToPins;", class_name));
        lines.push(String::new());

        // Parent node
        lines.push("\tUPROPERTY()".to_string());
        lines.push(format!(
            "\tU{}GraphNodeData* Parent = nullptr;",
            self.graph.name
        ));
        lines.push("};".to_string());

        Ok(lines.join("\n"))
    }

    /// Generate PinData class source
    fn generate_pin_data_source(&self) -> Result<String> {
        let mut lines = Vec::new();

        lines.push("// Generated by KAIN compiler".to_string());
        lines.push(String::new());
        lines.push(format!("#include \"{}PinData.h\"", self.graph.name));
        lines.push(format!("#include \"{}GraphNodeData.h\"", self.graph.name));
        lines.push(String::new());
        lines.push("// PinData implementation (empty - all logic in header)".to_string());

        Ok(lines.join("\n"))
    }

    /// Generate base NodeData class header
    pub fn generate_base_node_data_header(&self) -> Result<String> {
        let class_name = format!("U{}GraphNodeData", self.graph.name);
        let pin_class = format!("U{}PinData", self.graph.name);
        let instance_class = format!("U{}Instance", self.graph.name);
        let api_macro = format!("{}_API", self.plugin_name.to_uppercase());

        let mut lines = Vec::new();

        lines.push("// Generated by KAIN compiler".to_string());
        lines.push(String::new());
        lines.push("#pragma once".to_string());
        lines.push(String::new());
        lines.push("#include \"CoreMinimal.h\"".to_string());
        lines.push("#include \"UObject/NoExportTypes.h\"".to_string());
        lines.push(format!(
            "#include \"{}GraphNodeData.generated.h\"",
            self.graph.name
        ));
        lines.push(String::new());

        // Forward declarations
        lines.push(format!("class {};", instance_class));
        lines.push(format!("class {};", pin_class));
        lines.push(String::new());

        // Class declaration
        lines.push("UCLASS()".to_string());
        lines.push(format!("class {} {}", api_macro, class_name));
        lines.push("\t: public UObject".to_string());
        lines.push("{".to_string());
        lines.push("\tGENERATED_BODY()".to_string());
        lines.push(String::new());
        lines.push("public:".to_string());

        // Input pins
        lines.push("\tUPROPERTY()".to_string());
        lines.push(format!("\tTArray<{}*> InputPins;", pin_class));
        lines.push(String::new());

        // Output pins
        lines.push("\tUPROPERTY()".to_string());
        lines.push(format!("\tTArray<{}*> OutputPins;", pin_class));
        lines.push(String::new());

        // Node position
        lines.push("\tUPROPERTY()".to_string());
        lines.push("\tFIntPoint NodePosition;".to_string());
        lines.push(String::new());

        // Node GUID
        lines.push("\tUPROPERTY()".to_string());
        lines.push("\tFGuid NodeGuid;".to_string());
        lines.push(String::new());

        // Methods
        lines.push("public:".to_string());
        lines.push(
            "\t/// Get the next node connected to the specified output pin index".to_string(),
        );
        lines.push(format!(
            "\t{}* GetNextOutputNodeByPinIndex(int OutputPinIndex) const;",
            class_name
        ));
        lines.push(String::new());

        lines.push("\t/// Execute this node and return the next node to execute".to_string());
        lines.push(format!(
            "\tvirtual const {}* ExecuteNode({}* Instance) const;",
            class_name, instance_class
        ));
        lines.push("};".to_string());

        Ok(lines.join("\n"))
    }

    /// Generate base NodeData class source
    pub fn generate_base_node_data_source(&self) -> Result<String> {
        let class_name = format!("U{}GraphNodeData", self.graph.name);
        let pin_class = format!("U{}PinData", self.graph.name);
        let instance_class = format!("U{}Instance", self.graph.name);

        let mut lines = Vec::new();

        lines.push("// Generated by KAIN compiler".to_string());
        lines.push(String::new());
        lines.push(format!("#include \"{}GraphNodeData.h\"", self.graph.name));
        lines.push(format!("#include \"{}PinData.h\"", self.graph.name));
        lines.push(String::new());

        // GetNextOutputNodeByPinIndex implementation
        lines.push(format!(
            "{}* {}::GetNextOutputNodeByPinIndex(int OutputPinIndex) const",
            class_name, class_name
        ));
        lines.push("{".to_string());
        lines.push("\tif (!OutputPins.IsValidIndex(OutputPinIndex))".to_string());
        lines.push("\t{".to_string());
        lines.push("\t\treturn nullptr;".to_string());
        lines.push("\t}".to_string());
        lines.push(String::new());
        lines.push(format!(
            "\t{}* OutputPin = OutputPins[OutputPinIndex];",
            pin_class
        ));
        lines.push("\tif (!IsValid(OutputPin) || OutputPin->ConnectToPins.Num() == 0)".to_string());
        lines.push("\t{".to_string());
        lines.push("\t\treturn nullptr;".to_string());
        lines.push("\t}".to_string());
        lines.push(String::new());
        lines.push("\t// Get the first connected pin's parent node".to_string());
        lines.push(format!(
            "\t{}* ConnectedPin = OutputPin->ConnectToPins[0];",
            pin_class
        ));
        lines.push("\tif (!IsValid(ConnectedPin))".to_string());
        lines.push("\t{".to_string());
        lines.push("\t\treturn nullptr;".to_string());
        lines.push("\t}".to_string());
        lines.push(String::new());
        lines.push("\treturn ConnectedPin->Parent;".to_string());
        lines.push("}".to_string());
        lines.push(String::new());

        // ExecuteNode implementation (base - does nothing)
        lines.push(format!(
            "const {}* {}::ExecuteNode({}* Instance) const",
            class_name, class_name, instance_class
        ));
        lines.push("{".to_string());
        lines.push("\t// Base implementation - return next node via first output pin".to_string());
        lines.push("\treturn GetNextOutputNodeByPinIndex(0);".to_string());
        lines.push("}".to_string());

        Ok(lines.join("\n"))
    }

    /// Generate NodeData subclass for a specific node type
    pub fn generate_node_data_subclass(&self, node: &NodeType) -> Result<(String, String)> {
        let header = self.generate_node_data_subclass_header(node)?;
        let source = self.generate_node_data_subclass_source(node)?;
        Ok((header, source))
    }

    /// Generate NodeData subclass header
    pub fn generate_node_data_subclass_header(&self, node: &NodeType) -> Result<String> {
        let class_name = format!("U{}NodeData", node.name);
        let base_class = format!("U{}GraphNodeData", self.graph.name);
        let instance_class = format!("U{}Instance", self.graph.name);
        let api_macro = format!("{}_API", self.plugin_name.to_uppercase());

        let mut lines = Vec::new();

        lines.push("// Generated by KAIN compiler".to_string());
        lines.push(String::new());
        lines.push("#pragma once".to_string());
        lines.push(String::new());
        lines.push("#include \"CoreMinimal.h\"".to_string());
        lines.push(format!("#include \"{}GraphNodeData.h\"", self.graph.name));

        // Add includes for object/struct types
        for input in &node.inputs {
            if let Some(include) = self.get_type_include(&input.pin_type) {
                if !lines.iter().any(|l| l.contains(&include)) {
                    lines.push(format!("#include \"{}\"", include));
                }
            }
        }

        lines.push(format!("#include \"{}NodeData.generated.h\"", node.name));
        lines.push(String::new());

        // Forward declarations
        lines.push(format!("class {};", instance_class));
        lines.push(String::new());

        // Class declaration
        lines.push("UCLASS()".to_string());
        lines.push(format!("class {} {}", api_macro, class_name));
        lines.push(format!("\t: public {}", base_class));
        lines.push("{".to_string());
        lines.push("\tGENERATED_BODY()".to_string());
        lines.push(String::new());

        // Properties section
        if self.has_node_properties(node) {
            lines.push("public:".to_string());

            // Generate properties from non-exec input pins
            for input in &node.inputs {
                if input.pin_type != PinType::Exec {
                    let prop_type = self.pin_type_to_cpp_type(&input.pin_type);
                    let prop_name = self.sanitize_property_name(&input.name);

                    // Generate UPROPERTY with appropriate specifiers
                    let specifiers = vec!["EditAnywhere", "BlueprintReadOnly"];
                    let category = "Category = \"Node Data\"";

                    lines.push(format!(
                        "\tUPROPERTY({}, {})",
                        specifiers.join(", "),
                        category
                    ));

                    // Handle array types
                    if input.is_array {
                        lines.push(format!("\tTArray<{}> {};", prop_type, prop_name));
                    } else {
                        lines.push(format!("\t{} {};", prop_type, prop_name));
                    }

                    // Add tooltip comment if available
                    if let Some(tooltip) = &input.tooltip {
                        lines.insert(lines.len() - 2, format!("\t/** {} */", tooltip));
                    }

                    lines.push(String::new());
                }
            }
        }

        // Methods
        lines.push("public:".to_string());
        lines.push("\t/// Execute this node and return the next node to execute".to_string());
        lines.push(format!(
            "\tvirtual const {}* ExecuteNode({}* Instance) const override;",
            base_class, instance_class
        ));
        lines.push(String::new());

        // Add validation method
        lines.push("\t/// Validate node data before execution".to_string());
        lines.push("\tUFUNCTION(BlueprintCallable, Category = \"Node Validation\")".to_string());
        lines.push("\tvirtual bool ValidateNode() const;".to_string());

        lines.push("};".to_string());

        Ok(lines.join("\n"))
    }

    /// Get include path for a pin type
    fn get_type_include(&self, pin_type: &PinType) -> Option<String> {
        match pin_type {
            PinType::Object(class_name) => {
                // Try to determine include path from class name
                if class_name.starts_with("A") {
                    Some(format!("GameFramework/{}.h", &class_name[1..]))
                } else if class_name.starts_with("U") {
                    Some(format!("Components/{}.h", &class_name[1..]))
                } else {
                    None
                }
            }
            PinType::Struct(struct_name) => {
                // Common UE5 structs
                match struct_name.as_str() {
                    "Vector" => Some("Math/Vector.h".to_string()),
                    "Rotator" => Some("Math/Rotator.h".to_string()),
                    "Transform" => Some("Math/Transform.h".to_string()),
                    "Color" => Some("Math/Color.h".to_string()),
                    _ => None,
                }
            }
            _ => None,
        }
    }

    /// Generate NodeData subclass source
    pub fn generate_node_data_subclass_source(&self, node: &NodeType) -> Result<String> {
        let class_name = format!("U{}NodeData", node.name);
        let base_class = format!("U{}GraphNodeData", self.graph.name);
        let instance_class = format!("U{}Instance", self.graph.name);

        let mut lines = Vec::new();

        lines.push("// Generated by KAIN compiler".to_string());
        lines.push(String::new());
        lines.push(format!("#include \"{}NodeData.h\"", node.name));
        lines.push(format!("#include \"{}Instance.h\"", self.graph.name));
        lines.push(String::new());

        // ExecuteNode implementation
        lines.push(format!(
            "const {}* {}::ExecuteNode({}* Instance) const",
            base_class, class_name, instance_class
        ));
        lines.push("{".to_string());

        // Add validation check
        lines.push("\tif (!IsValid(Instance))".to_string());
        lines.push("\t{".to_string());
        lines.push("\t\treturn nullptr;".to_string());
        lines.push("\t}".to_string());
        lines.push(String::new());

        // Add execution logic if provided
        if let Some(logic) = &node.execution_logic {
            lines.push("\t// Custom execution logic".to_string());
            lines.push(format!("\t// {}", logic));
            lines.push(String::new());

            // Generate execution logic based on the logic string
            let logic_lines = self.generate_execution_logic(node, logic);
            for line in logic_lines {
                lines.push(format!("\t{}", line));
            }
        } else {
            lines.push("\t// Default execution - pass through to next node".to_string());
        }

        lines.push(String::new());

        // Generate output pin selection logic
        if node.outputs.len() > 1 {
            lines.push("\t// Select output pin based on execution result".to_string());
            lines.push("\t// Default: use first output pin".to_string());
            lines.push("\tint32 OutputPinIndex = 0;".to_string());
            lines.push(String::new());
        }

        lines.push("\t// Return next node via output pin".to_string());
        if node.outputs.len() > 1 {
            lines.push("\treturn GetNextOutputNodeByPinIndex(OutputPinIndex);".to_string());
        } else {
            lines.push("\treturn GetNextOutputNodeByPinIndex(0);".to_string());
        }
        lines.push("}".to_string());
        lines.push(String::new());

        // ValidateNode implementation
        lines.push(format!("bool {}::ValidateNode() const", class_name));
        lines.push("{".to_string());
        lines.push("\t// Validate that all required properties are set".to_string());
        lines.push(String::new());

        // Generate validation for non-exec input pins
        let mut has_validation = false;
        for input in &node.inputs {
            if input.pin_type != PinType::Exec {
                let prop_name = self.sanitize_property_name(&input.name);

                // Generate validation based on type
                match &input.pin_type {
                    PinType::Object(_) => {
                        lines.push(format!("\tif (!IsValid({}))", prop_name));
                        lines.push("\t{".to_string());
                        lines.push(format!(
                            "\t\tUE_LOG(LogTemp, Warning, TEXT(\"{}NodeData: {} is not valid\"));",
                            node.name, prop_name
                        ));
                        lines.push("\t\treturn false;".to_string());
                        lines.push("\t}".to_string());
                        lines.push(String::new());
                        has_validation = true;
                    }
                    PinType::String => {
                        if input.default_value.is_none() {
                            lines.push(format!("\tif ({}.IsEmpty())", prop_name));
                            lines.push("\t{".to_string());
                            lines.push(format!(
                                "\t\tUE_LOG(LogTemp, Warning, TEXT(\"{}NodeData: {} is empty\"));",
                                node.name, prop_name
                            ));
                            lines.push("\t\treturn false;".to_string());
                            lines.push("\t}".to_string());
                            lines.push(String::new());
                            has_validation = true;
                        }
                    }
                    _ => {}
                }
            }
        }

        if !has_validation {
            lines.push("\t// No validation required for this node".to_string());
        }

        lines.push("\treturn true;".to_string());
        lines.push("}".to_string());

        Ok(lines.join("\n"))
    }

    /// Generate execution logic from logic string
    fn generate_execution_logic(&self, _node: &NodeType, logic: &str) -> Vec<String> {
        let mut lines = Vec::new();

        // For now, generate a placeholder that can be customized
        // In a full implementation, this would parse the logic string and generate C++ code
        lines.push("// TODO: Implement custom execution logic".to_string());
        lines.push(format!("// Logic: {}", logic));

        // Add example logic for common patterns
        if logic.contains("condition") || logic.contains("branch") {
            lines.push(String::new());
            lines.push("// Example: Branch based on condition".to_string());
            lines.push("// if (Condition)".to_string());
            lines.push("// {".to_string());
            lines.push("//     OutputPinIndex = 0; // True branch".to_string());
            lines.push("// }".to_string());
            lines.push("// else".to_string());
            lines.push("// {".to_string());
            lines.push("//     OutputPinIndex = 1; // False branch".to_string());
            lines.push("// }".to_string());
        }

        lines
    }

    /// Check if node has properties (non-exec pins)
    pub fn has_node_properties(&self, node: &NodeType) -> bool {
        node.inputs.iter().any(|pin| pin.pin_type != PinType::Exec)
    }

    /// Convert pin type to C++ type
    pub fn pin_type_to_cpp_type(&self, pin_type: &PinType) -> String {
        match pin_type {
            PinType::Exec => "void".to_string(),
            PinType::Bool => "bool".to_string(),
            PinType::Int => "int32".to_string(),
            PinType::Float => "float".to_string(),
            PinType::String => "FString".to_string(),
            PinType::Object(class) => {
                // Handle wildcard object types
                if class.is_empty() || class == "*" {
                    "UObject*".to_string()
                } else {
                    format!("{}*", class)
                }
            }
            PinType::Struct(name) => {
                // Handle common UE5 struct names
                match name.as_str() {
                    "Vector" => "FVector".to_string(),
                    "Rotator" => "FRotator".to_string(),
                    "Transform" => "FTransform".to_string(),
                    "Color" => "FLinearColor".to_string(),
                    _ => {
                        // Add F prefix if not present
                        if name.starts_with('F') {
                            name.clone()
                        } else {
                            format!("F{}", name)
                        }
                    }
                }
            }
            PinType::Enum(name) => {
                // Add E prefix if not present
                if name.starts_with('E') {
                    name.clone()
                } else {
                    format!("E{}", name)
                }
            }
            PinType::Wildcard => "UObject*".to_string(),
        }
    }

    /// Sanitize property name (convert to valid C++ identifier)
    pub fn sanitize_property_name(&self, name: &str) -> String {
        // Convert to PascalCase and ensure valid C++ identifier
        let mut result = String::new();
        let mut capitalize_next = true;

        for ch in name.chars() {
            if ch.is_alphanumeric() {
                if capitalize_next {
                    result.push(ch.to_ascii_uppercase());
                    capitalize_next = false;
                } else {
                    result.push(ch);
                }
            } else {
                capitalize_next = true;
            }
        }

        // Ensure it doesn't start with a number
        if result.chars().next().map_or(false, |c| c.is_numeric()) {
            result.insert(0, '_');
        }

        result
    }
}

/// Public API function for generating NodeData classes
pub fn generate_node_data(graph: &GraphEditor, plugin_name: &str) -> Result<NodeDataOutput> {
    let generator = NodeDataGenerator::new(graph, plugin_name);
    generator.generate()
}

