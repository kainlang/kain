//! Asset Class Generator
//!
//! Generates runtime Asset classes for graph storage.
//!
//! Pattern:
//! ```cpp
//! // Asset class
//! UCLASS()
//! class U{Name}GraphAsset : public UObject {
//!     GENERATED_BODY()
//! public:
//!     UPROPERTY()
//!     U{Name}GraphData* GraphData;
//!     
//!     UFUNCTION(BlueprintCallable)
//!     U{Name}GraphInstance* CreateInstance();
//!     
//!     UFUNCTION(BlueprintPure)
//!     bool ValidateGraph() const;
//! };
//! ```

use crate::{GraphEditor, Result};

/// Output structure for Asset generation
#[derive(Debug, Clone)]
pub struct AssetOutput {
    /// Asset class header (filename, content)
    pub asset_header: (String, String),
    /// Asset class source (filename, content)
    pub asset_source: (String, String),
}

pub struct AssetGenerator {
    plugin_name: String,
    graph: GraphEditor,
}

impl AssetGenerator {
    /// Create a new Asset generator
    pub fn new(graph: &GraphEditor, plugin_name: impl Into<String>) -> Self {
        Self {
            plugin_name: plugin_name.into(),
            graph: graph.clone(),
        }
    }
    
    /// Generate complete Asset output
    pub fn generate(&self) -> Result<AssetOutput> {
        let asset_header = self.generate_asset_header()?;
        let asset_source = self.generate_asset_source()?;
        
        Ok(AssetOutput {
            asset_header: (format!("{}GraphAsset.h", self.graph.name), asset_header),
            asset_source: (format!("{}GraphAsset.cpp", self.graph.name), asset_source),
        })
    }
    
    /// Generate Asset class header
    pub fn generate_asset_header(&self) -> Result<String> {
        let class_name = format!("U{}GraphAsset", self.graph.name);
        let graph_data_class = format!("U{}GraphData", self.graph.name);
        let instance_class = format!("U{}Instance", self.graph.name);
        let api_macro = format!("{}_API", self.plugin_name.to_uppercase());
        
        let mut lines = Vec::new();
        
        lines.push("// Generated by KAIN compiler".to_string());
        lines.push(String::new());
        lines.push("#pragma once".to_string());
        lines.push(String::new());
        lines.push("#include \"CoreMinimal.h\"".to_string());
        lines.push("#include \"UObject/NoExportTypes.h\"".to_string());
        lines.push(format!("#include \"{}GraphAsset.generated.h\"", self.graph.name));
        lines.push(String::new());
        
        // Forward declarations
        lines.push(format!("class {};", graph_data_class));
        lines.push(format!("class {};", instance_class));
        lines.push(String::new());
        
        // Class declaration
        lines.push("/**".to_string());
        lines.push(format!(" * Asset class for {} graph storage", self.graph.name));
        lines.push(" * Stores graph data and provides instance creation".to_string());
        lines.push(" */".to_string());
        lines.push("UCLASS(BlueprintType)".to_string());
        lines.push(format!("class {} {}", api_macro, class_name));
        lines.push("\t: public UObject".to_string());
        lines.push("{".to_string());
        lines.push("\tGENERATED_BODY()".to_string());
        lines.push(String::new());
        lines.push("public:".to_string());
        
        // GraphData property
        lines.push("\t/**".to_string());
        lines.push("\t * Graph data containing all nodes and connections".to_string());
        lines.push("\t */".to_string());
        lines.push("\tUPROPERTY(EditAnywhere, BlueprintReadOnly, Category = \"Graph\")".to_string());
        lines.push(format!("\t{}* GraphData;", graph_data_class));
        lines.push(String::new());
        
        // CreateInstance method
        lines.push("\t/**".to_string());
        lines.push("\t * Create a new graph instance for execution".to_string());
        lines.push("\t * @return New graph instance, or nullptr if creation fails".to_string());
        lines.push("\t */".to_string());
        lines.push(format!("\tUFUNCTION(BlueprintCallable, Category = \"{}|Asset\")", self.graph.name));
        lines.push(format!("\t{}* CreateInstance();", instance_class));
        lines.push(String::new());
        
        // ValidateGraph method
        lines.push("\t/**".to_string());
        lines.push("\t * Validate graph integrity".to_string());
        lines.push("\t * Checks for disconnected nodes, invalid connections, etc.".to_string());
        lines.push("\t * @return True if graph is valid, false otherwise".to_string());
        lines.push("\t */".to_string());
        lines.push(format!("\tUFUNCTION(BlueprintPure, Category = \"{}|Asset\")", self.graph.name));
        lines.push("\tbool ValidateGraph() const;".to_string());
        lines.push(String::new());
        
        // GetNodeCount method
        lines.push("\t/**".to_string());
        lines.push("\t * Get the number of nodes in the graph".to_string());
        lines.push("\t * @return Number of nodes".to_string());
        lines.push("\t */".to_string());
        lines.push(format!("\tUFUNCTION(BlueprintPure, Category = \"{}|Asset\")", self.graph.name));
        lines.push("\tint32 GetNodeCount() const;".to_string());
        lines.push("};".to_string());
        
        Ok(lines.join("\n"))
    }
    
    /// Generate Asset class source
    pub fn generate_asset_source(&self) -> Result<String> {
        let class_name = format!("U{}GraphAsset", self.graph.name);
        let instance_class = format!("U{}Instance", self.graph.name);
        
        let mut lines = Vec::new();
        
        lines.push("// Generated by KAIN compiler".to_string());
        lines.push(String::new());
        lines.push(format!("#include \"{}GraphAsset.h\"", self.graph.name));
        lines.push(format!("#include \"{}GraphData.h\"", self.graph.name));
        lines.push(format!("#include \"{}Instance.h\"", self.graph.name));
        lines.push(String::new());
        
        // CreateInstance implementation
        lines.push(format!("{}* {}::CreateInstance()", instance_class, class_name));
        lines.push("{".to_string());
        lines.push("\t// Validate graph data exists".to_string());
        lines.push("\tif (!IsValid(GraphData))".to_string());
        lines.push("\t{".to_string());
        lines.push("\t\tUE_LOG(LogTemp, Error, TEXT(\"Cannot create instance: GraphData is null\"));".to_string());
        lines.push("\t\treturn nullptr;".to_string());
        lines.push("\t}".to_string());
        lines.push(String::new());
        lines.push("\t// Validate graph before creating instance".to_string());
        lines.push("\tif (!ValidateGraph())".to_string());
        lines.push("\t{".to_string());
        lines.push("\t\tUE_LOG(LogTemp, Error, TEXT(\"Cannot create instance: Graph validation failed\"));".to_string());
        lines.push("\t\treturn nullptr;".to_string());
        lines.push("\t}".to_string());
        lines.push(String::new());
        lines.push("\t// Create new instance".to_string());
        lines.push(format!("\t{}* NewInstance = NewObject<{}>(this);", instance_class, instance_class));
        lines.push("\tif (!IsValid(NewInstance))".to_string());
        lines.push("\t{".to_string());
        lines.push("\t\tUE_LOG(LogTemp, Error, TEXT(\"Failed to create graph instance\"));".to_string());
        lines.push("\t\treturn nullptr;".to_string());
        lines.push("\t}".to_string());
        lines.push(String::new());
        lines.push("\t// TODO: Initialize instance with graph data".to_string());
        lines.push("\t// This should call ConstructInstance() on the instance".to_string());
        lines.push(String::new());
        lines.push("\treturn NewInstance;".to_string());
        lines.push("}".to_string());
        lines.push(String::new());
        
        // ValidateGraph implementation
        lines.push(format!("bool {}::ValidateGraph() const", class_name));
        lines.push("{".to_string());
        lines.push("\t// Check if graph data exists".to_string());
        lines.push("\tif (!IsValid(GraphData))".to_string());
        lines.push("\t{".to_string());
        lines.push("\t\treturn false;".to_string());
        lines.push("\t}".to_string());
        lines.push(String::new());
        lines.push("\t// Check if graph has nodes".to_string());
        lines.push("\tif (GraphData->Nodes.Num() == 0)".to_string());
        lines.push("\t{".to_string());
        lines.push("\t\tUE_LOG(LogTemp, Warning, TEXT(\"Graph has no nodes\"));".to_string());
        lines.push("\t\treturn false;".to_string());
        lines.push("\t}".to_string());
        lines.push(String::new());
        lines.push("\t// Validate all nodes are valid".to_string());
        lines.push("\tfor (int32 i = 0; i < GraphData->Nodes.Num(); ++i)".to_string());
        lines.push("\t{".to_string());
        lines.push("\t\tif (!IsValid(GraphData->Nodes[i]))".to_string());
        lines.push("\t\t{".to_string());
        lines.push("\t\t\tUE_LOG(LogTemp, Error, TEXT(\"Graph contains invalid node at index %d\"), i);".to_string());
        lines.push("\t\t\treturn false;".to_string());
        lines.push("\t\t}".to_string());
        lines.push("\t}".to_string());
        lines.push(String::new());
        lines.push("\t// TODO: Add more validation checks:".to_string());
        lines.push("\t// - Check for disconnected nodes".to_string());
        lines.push("\t// - Check for invalid pin connections".to_string());
        lines.push("\t// - Check for circular dependencies".to_string());
        lines.push("\t// - Check for missing required connections".to_string());
        lines.push(String::new());
        lines.push("\treturn true;".to_string());
        lines.push("}".to_string());
        lines.push(String::new());
        
        // GetNodeCount implementation
        lines.push(format!("int32 {}::GetNodeCount() const", class_name));
        lines.push("{".to_string());
        lines.push("\tif (!IsValid(GraphData))".to_string());
        lines.push("\t{".to_string());
        lines.push("\t\treturn 0;".to_string());
        lines.push("\t}".to_string());
        lines.push(String::new());
        lines.push("\treturn GraphData->Nodes.Num();".to_string());
        lines.push("}".to_string());
        
        Ok(lines.join("\n"))
    }
}

/// Public API function for generating Asset classes
pub fn generate_graph_asset(
    graph: &GraphEditor,
    plugin_name: &str,
) -> Result<AssetOutput> {
    let generator = AssetGenerator::new(graph, plugin_name);
    generator.generate()
}

